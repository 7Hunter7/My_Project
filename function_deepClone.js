/*
**Объяснение:**
1) Object.keys(obj) возвращает массив ключей объекта.
2) Цикл for...of итерирует по массиву ключей.
3) Остальной код аналогичен исходному примеру.

**Преимущества:**
- Более современный и читаемый синтаксис цикла, чем for...in.
- Более явно указывает на итерацию по ключам объекта.

**Недостатки:**
- Требует более современной версии JavaScript, чем цикл for...in.

* Если вы используете современный JavaScript и хотите краткий и элегантный код, используйте Object.entries и Object.fromEntries с фильтром hasOwnProperty.
* Если вам важна читаемость и вы предпочитаете функциональный стиль, используйте reduce.
* Если вам нужен баланс между читаемостью и производительностью, используйте цикл for...of и Object.keys.
* Если важна максимальная совместимость со старыми браузерами, оставайтесь с исходным циклом for...in.
* В большинстве случаев, разница в производительности между этими вариантами будет незначительной, поэтому выбирайте тот, который лучше всего соответствует вашему стилю и требованиям к совместимости.
* Главное - не забывать про hasOwnProperty для правильной обработки свойств объекта.
*/