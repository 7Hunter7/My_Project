function deepClone(obj) {
  if (obj === null || typeof obj !== "object") {
    return obj; // Возвращаем значение, если obj не является объектом
  }

  if (Array.isArray(obj)) {
    return obj.map((item) => deepClone(item)); // Обрабатываем массивы
  }

  const copy = {};
  for (const key in obj) {
    if (obj.hasOwnProperty(key)) {
      copy[key] = deepClone(obj[key]); // Рекурсивно копируем каждое свойство
    }
  }

  return copy;
}

const original = { a: 1, b: { c: 2, d: [3, 4] } };
const cloned = deepClone(original);
console.log(cloned); // { a: 1, b: { c: 2, d: [ 3, 4 ] } }

// Изменим вложенный объект в оригинальном объекте
original.b.c = 10;
original.b.d[0] = 5;

console.log(original); // { a: 1, b: { c: 10, d: [ 5, 4 ] } }
console.log(cloned);  // { a: 1, b: { c: 2, d: [ 3, 4 ] } }

/*
Если бы мы использовали поверхностное копирование (например, Object.assign({}, original) или spread operator ...original), cloned.b был бы просто ссылкой на original.b. В этом случае, изменение original.b.c также изменило бы cloned.b.c, потому что оба указывали бы на один и тот же объект в памяти. Глубокое копирование решает эту проблему, создавая полностью независимую копию.

Ограничения:
Циклические ссылки: Эта реализация deepClone не обрабатывает циклические ссылки (когда объект ссылается сам на себя). Это приведет к бесконечной рекурсии и переполнению стека. Чтобы обработать циклические ссылки, потребуется более сложная реализация, которая отслеживает уже посещенные объекты.

Функции и другие специальные объекты: Функция не клонирует функции, объекты Date, RegExp и другие специальные объекты. Для них будет скопирована ссылка, а не создана новая копия. Для более продвинутого клонирования, которое обрабатывает эти случаи, можно использовать сторонние библиотеки, такие как Lodash (_.cloneDeep).
*/

// Альтернативные варианты:
// 1. Использование Object.entries и Object.fromEntries (Современный JavaScript):

const copy1 = Object.fromEntries(
  Object.entries(obj).map(([key, value]) => [key, deepClone(value)])
);

/*
**Объяснение:**
1) Object.entries(obj): Преобразует объект obj в массив пар ключ-значение (массив массивов).
    Например, { a: 1, b: 2 } превращается в [['a', 1], ['b', 2]].
2) .map(([key, value]) => [key, deepClone(value)]): Итерирует по массиву пар ключ-значение.
    Для каждой пары:
- [key, value] - деструктуризация пары.
- deepClone(value) - рекурсивно клонирует значение.
3) [key, deepClone(value)] - создает новую пару ключ-значение с клонированным значением.
4) Object.fromEntries(...): Преобразует массив пар ключ-значение обратно в объект.

**Преимущества:**
- Более краткий и читаемый синтаксис, особенно если вы знакомы с функциональным программированием.
- Потенциально может быть немного быстрее, чем цикл for...in (зависит от реализации движка JavaScript).

**Недостатки:**
- Требует более современных версий JavaScript (ES2019 и выше).
- Неявно включает свойства из прототипа. Чтобы этого избежать, можно добавить проверку obj.hasOwnProperty(key) внутрь map.
*/
// 2. Скорректированная версия с hasOwnProperty:
const copy2 = Object.fromEntries(
  Object.entries(obj)
    .filter(([key]) => obj.hasOwnProperty(key)) // Добавляем фильтр
    .map(([key, value]) => [key, deepClone(value)])
);

// 3. Использование reduce (Функциональный подход):

const copy3 = Object.keys(obj).reduce((acc, key) => {
  if (obj.hasOwnProperty(key)) {
    acc[key] = deepClone(obj[key]);
  }
  return acc;
}, {});

/*
**Объяснение:**
1) Object.keys(obj): Возвращает массив ключей объекта obj.
2) .reduce((acc, key) => { ... }, {}): Итерирует по массиву ключей, используя reduce.
3) acc (accumulator): Накапливает результат (в данном случае, новый объект). Инициализируется как {}.
4) key: Текущий ключ в итерации.
Внутри коллбэка reduce:
5) if (obj.hasOwnProperty(key)): Проверяет, является ли свойство собственным.
6) acc[key] = deepClone(obj[key]): Присваивает склонированное значение в аккумулятор.
7) return acc: Возвращает обновленный аккумулятор для следующей итерации.

**Преимущества:**
- Функциональный стиль.
- Четко определяет, что происходит с каждым ключом.
**Недостатки:**
- Может быть менее читаемым для тех, кто не знаком с reduce.
- Может быть немного медленнее, чем цикл for...in в некоторых случаях.
*/

